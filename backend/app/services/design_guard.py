"""AI 角色边界守卫（缺陷 9）：只回答 UI/设计相关问题，无关请求礼貌拒答。

规则（保守放行，避免误杀）：
- 含页面类型词（登录/电商/仪表/表单/列表/文章/落地页等）→ 设计请求
- 或 含设计动词（设计/生成/创建/改成/调大…）+ UI/组件词（按钮/布局/颜色/间距…）→ 设计请求
其余（"帮我写首诗""1+1 等于几"）→ 拦截并提示角色边界。
"""
from typing import Final

# 页面类型词（与模板关键词同源，命中即视为设计请求）
PAGE_KEYWORDS: Final[tuple[str, ...]] = (
    "页面", "登录", "注册", "电商", "优惠", "商城", "购物", "仪表", "报表", "数据大屏",
    "表单", "登记", "问卷", "列表", "订单", "文章", "博客", "落地页", "推广", "设置页",
    "个人主页", "首页", "导航", "课程", "论坛", "详情页", "活动页", "会场",
)

# 设计动词
DESIGN_VERBS: Final[tuple[str, ...]] = (
    "设计", "生成", "创建", "做", "画", "把", "将", "改成", "改为", "变成", "调大", "调小",
    "放大", "缩小", "移动", "删除", "加个", "添加", "换颜色", "加宽", "加高",
)

# UI/组件词
UI_KEYWORDS: Final[tuple[str, ...]] = (
    "ui", "界面", "布局", "按钮", "颜色", "色彩", "间距", "圆角", "字体", "字号",
    "图标", "图片", "背景", "导航栏", "侧边栏", "卡片", "表格", "图表", "输入框",
    "下拉", "头像", "标签", "分割线", "标题", "画布", "设计稿", "样式", "轮播", "页脚",
)


def is_design_request(prompt: str) -> bool:
    """判断是否 UI 设计相关请求（保守放行）。"""
    lowered = prompt.lower()
    if any(k in prompt for k in PAGE_KEYWORDS):
        return True
    has_verb = any(v in prompt for v in DESIGN_VERBS)
    has_ui = any(k in lowered for k in UI_KEYWORDS)
    return has_verb and has_ui


GUARD_REPLY = (
    "我是 AI 设计助手，只负责 UI / 界面设计相关的问题"
    "（页面布局、组件、颜色、间距、圆角等）。"
    "其他类型的问题我无法回答，请描述你想要的设计稿，例如："
    "「设计一个登录页」「把按钮改成红色」。"
)
